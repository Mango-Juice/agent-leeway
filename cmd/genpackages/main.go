// Command genpackages writes the Homebrew formula (Formula/agent-leeway.rb) and the Scoop manifest
// (bucket/agent-leeway.json) for one release from that release's checksums.txt. The release workflow runs it
// after a release is published; the repository itself is the Homebrew tap and the Scoop bucket.
//
//	go run ./cmd/genpackages -version v0.1.0 -checksums checksums.txt -out .
package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/Mango-Juice/agent-leeway/internal/meta"
)

const desc = "Occasional check-up of Claude Code and Codex logs (cost leaks and intent drift)"

var (
	versionRe = regexp.MustCompile(`^v?(\d+\.\d+\.\d+)$`)
	shaRe     = regexp.MustCompile(`^[0-9a-f]{64}$`)
)

// archives needed: the four Unix tarballs and the two Windows zips.
var archives = []string{"darwin_amd64.tar.gz", "darwin_arm64.tar.gz", "linux_amd64.tar.gz", "linux_arm64.tar.gz", "windows_amd64.zip", "windows_arm64.zip"}

// ParseChecksums reads "sha256  filename" lines and requires every archive.
func ParseChecksums(text string) (map[string]string, error) {
	sums := map[string]string{}
	sc := bufio.NewScanner(strings.NewReader(text))
	for sc.Scan() {
		f := strings.Fields(sc.Text())
		if len(f) != 2 {
			continue
		}
		if !shaRe.MatchString(f[0]) {
			return nil, fmt.Errorf("bad sha256 for %s", f[1])
		}
		sums[f[1]] = f[0]
	}
	for _, a := range archives {
		if _, ok := sums[meta.Repo+"_"+a]; !ok {
			return nil, fmt.Errorf("checksums.txt has no %s_%s", meta.Repo, a)
		}
	}
	return sums, nil
}

func dl(tag, file string) string {
	return meta.RepoURL() + "/releases/download/" + tag + "/" + file
}

// Formula is the Homebrew formula text.
func Formula(version string, sums map[string]string) string {
	tag := "v" + version
	file := func(a string) string { return meta.Repo + "_" + a }
	block := func(osName string) string {
		var b strings.Builder
		fmt.Fprintf(&b, "  on_%s do\n", map[string]string{"darwin": "macos", "linux": "linux"}[osName])
		for _, cpu := range []struct{ on, arch string }{{"arm", "arm64"}, {"intel", "amd64"}} {
			a := osName + "_" + cpu.arch + ".tar.gz"
			fmt.Fprintf(&b, "    on_%s do\n      url \"%s\"\n      sha256 \"%s\"\n    end\n", cpu.on, dl(tag, file(a)), sums[file(a)])
		}
		b.WriteString("  end\n")
		return b.String()
	}
	return `# Generated by cmd/genpackages from the release's checksums.txt; the release workflow rewrites it.
class AgentLeeway < Formula
  desc "` + desc + `"
  homepage "` + meta.RepoURL() + `"
  license "MIT"

` + block("darwin") + "\n" + block("linux") + `
  def install
    bin.install "agent-leeway"
    prefix.install "LICENSE", "NOTICE.md", "THIRD_PARTY_LICENSES.txt"
  end

  def caveats
    <<~EOS
      ` + skillNote + `
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/agent-leeway --version")
  end
end
`
}

// skillNote is shown after a Homebrew or Scoop install, which cannot add the skill for the user. Plain text
// with no quotes, backslashes or #{}: it goes into a Ruby heredoc and a JSON string unchanged.
const skillNote = "To add the skill to Claude Code and Codex, run once: agent-leeway install-skills. Then ask your agent for a leeway report."

// Manifest is the Scoop manifest text (checkver and autoupdate against the GitHub releases).
func Manifest(version string, sums map[string]string) string {
	tag := "v" + version
	file := func(a string) string { return meta.Repo + "_" + a }
	auto := func(a string) string {
		return meta.RepoURL() + "/releases/download/v$version/" + file(a)
	}
	return `{
    "version": "` + version + `",
    "description": "` + desc + `",
    "homepage": "` + meta.RepoURL() + `",
    "license": "MIT",
    "architecture": {
        "64bit": {
            "url": "` + dl(tag, file("windows_amd64.zip")) + `",
            "hash": "` + sums[file("windows_amd64.zip")] + `"
        },
        "arm64": {
            "url": "` + dl(tag, file("windows_arm64.zip")) + `",
            "hash": "` + sums[file("windows_arm64.zip")] + `"
        }
    },
    "bin": "agent-leeway.exe",
    "notes": "` + skillNote + `",
    "checkver": {
        "github": "` + meta.RepoURL() + `"
    },
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "` + auto("windows_amd64.zip") + `"
            },
            "arm64": {
                "url": "` + auto("windows_arm64.zip") + `"
            }
        },
        "hash": {
            "url": "$baseurl/checksums.txt"
        }
    }
}
`
}

func main() {
	version := flag.String("version", "", "release tag, e.g. v0.1.0")
	checksums := flag.String("checksums", "checksums.txt", "the release's checksums.txt")
	out := flag.String("out", ".", "repository root (Formula/ and bucket/ are written below it)")
	flag.Parse()
	m := versionRe.FindStringSubmatch(*version)
	if m == nil {
		fmt.Fprintln(os.Stderr, "-version must look like v1.2.3")
		os.Exit(2)
	}
	b, err := os.ReadFile(*checksums)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	sums, err := ParseChecksums(string(b))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	for path, text := range map[string]string{"Formula/agent-leeway.rb": Formula(m[1], sums), "bucket/agent-leeway.json": Manifest(m[1], sums)} {
		p := filepath.Join(*out, path)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err == nil {
			err = os.WriteFile(p, []byte(text), 0o644)
		}
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		fmt.Println("wrote", p)
	}
}
